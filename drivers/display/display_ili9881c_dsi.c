/* ILI9881C page-switching command: writes {0xFF, 0x98, 0x81, page} */
#define ILI9881C_PAGE_CMD  0xFF
static const uint8_t ili9881c_page_magic[] = {0x98, 0x81};

enum ili9881c_op {
	ILI9881C_SWITCH_PAGE,
	ILI9881C_COMMAND,
};

struct ili9881c_instr {
	enum ili9881c_op op;
	union {
		struct {
			uint8_t cmd;
			uint8_t data;
		} cmd;
		uint8_t page;
	} arg;
};

struct ili9881c_desc {
	const struct ili9881c_instr *init;
	size_t init_length;
	uint16_t width;
	uint16_t height;
	uint32_t hfp;
	uint32_t hbp;
	uint32_t hsync;
	uint32_t vfp;
	uint32_t vbp;
	uint32_t vsync;
	uint32_t mode_flags;
};

struct ili9881c_config {
	const struct device *mipi_dsi;
	struct gpio_dt_spec reset;
	struct gpio_dt_spec backlight;
	uint8_t data_lanes;
	uint8_t channel;
	const struct ili9881c_desc *desc;
};

#define ILI9881C_SWITCH_PAGE_INSTR(_page) \
	{ \
		.op = ILI9881C_SWITCH_PAGE, \
		.arg = { .page = (_page) }, \
	}

#define ILI9881C_COMMAND_INSTR(_cmd, _data) \
	{ \
		.op = ILI9881C_COMMAND, \
		.arg = { .cmd = { .cmd = (_cmd), .data = (_data) } }, \
	}

