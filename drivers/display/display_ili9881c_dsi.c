static int ili9881c_write_reg(const struct device *dev, uint8_t cmd,
			      const uint8_t *buf, size_t len)
{
	const struct ili9881c_config *cfg = dev->config;
	struct mipi_dsi_msg msg = {
		.cmd    = cmd,
		.tx_buf = buf,
		.tx_len = len,
		.flags  = MIPI_DSI_MSG_USE_LPM,
	};

	switch (len) {
	case 0:
		msg.type = MIPI_DSI_DCS_SHORT_WRITE;
		break;
	case 1:
		msg.type = MIPI_DSI_DCS_SHORT_WRITE_PARAM;
		break;
	default:
		msg.type = MIPI_DSI_DCS_LONG_WRITE;
		break;
	}

	if (mipi_dsi_transfer(cfg->mipi_dsi, cfg->channel, &msg) < 0) {
		LOG_ERR("Failed writing reg 0x%02x", cmd);
		return -EIO;
	}
	// else
	// {
	// 	LOG_INF("Wrote reg 0x%02x, len=%zu", cmd, len);
	// }

	return 0;
}

/*
 * Switch the ILI9881C internal register page.
 * Sends: {0xFF, 0x98, 0x81, page} as a DCS Long Write.
 */
static int ili9881c_switch_page(const struct device *dev, uint8_t page)
{
	const uint8_t params[] = {ili9881c_page_magic[0],
				  ili9881c_page_magic[1],
				  page};

	return ili9881c_write_reg(dev, ILI9881C_PAGE_CMD,
				  params, sizeof(params));
}

/* Send a single register write within the current page. */
static int ili9881c_send_cmd(const struct device *dev,
			     uint8_t cmd, uint8_t data)
{
	return ili9881c_write_reg(dev, cmd, &data, 1);
}

static int ili9881c_run_init_sequence(const struct device *dev)
{
	const struct ili9881c_config *cfg = dev->config;
	const struct ili9881c_desc *desc = cfg->desc;
	int ret;

	for (size_t i = 0; i < desc->init_length; i++) {
		const struct ili9881c_instr *instr = &desc->init[i];

		if (instr->op == ILI9881C_SWITCH_PAGE) {
			ret = ili9881c_switch_page(dev, instr->arg.page);
		} else {
			ret = ili9881c_send_cmd(dev,
						instr->arg.cmd.cmd,
						instr->arg.cmd.data);
		}

		if (ret < 0) {
			LOG_ERR("Init sequence failed at step %zu", i);
			return ret;
		}
	}

	/* Return to page 0 after the init sequence */
	ret = ili9881c_switch_page(dev, 0);
	if (ret < 0) {
		return ret;
	}

	/* Exit sleep mode and wait for display to wake up */
	ret = ili9881c_write_reg(dev, MIPI_DCS_EXIT_SLEEP_MODE, NULL, 0);
	if (ret < 0) {
		return ret;
	}
	k_msleep(120);

	/* SET_DISPLAY_ON must be sent here (before cdns_ti_dsi_enable_video)
	 * because TVG diagnostic blocks LP commands once active.
	 */
	return ili9881c_write_reg(dev, MIPI_DCS_SET_DISPLAY_ON, NULL, 0);
}

static int ili9881c_blanking_on(const struct device *dev)
{
	const struct ili9881c_config *cfg = dev->config;
	int ret;

	if (cfg->backlight.port != NULL) {
		ret = gpio_pin_set_dt(&cfg->backlight, 0);
		if (ret) {
			LOG_ERR("Disable backlight failed (%d)", ret);
			return ret;
		}
	}

	return ili9881c_write_reg(dev, MIPI_DCS_SET_DISPLAY_OFF, NULL, 0);
}

static int ili9881c_blanking_off(const struct device *dev)
{
	const struct ili9881c_config *cfg = dev->config;
	int ret;

	if (cfg->backlight.port != NULL) {
		ret = gpio_pin_set_dt(&cfg->backlight, 1);
		if (ret) {
			LOG_ERR("Enable backlight failed (%d)", ret);
			return ret;
		}
	}

	return ili9881c_write_reg(dev, MIPI_DCS_SET_DISPLAY_ON, NULL, 0);
}

static void ili9881c_get_capabilities(const struct device *dev,
				      struct display_capabilities *caps)
{
	const struct ili9881c_config *cfg = dev->config;

	memset(caps, 0, sizeof(*caps));
	caps->x_resolution          = cfg->desc->width;
	caps->y_resolution          = cfg->desc->height;
	caps->supported_pixel_formats = PIXEL_FORMAT_RGB_888;
	caps->current_pixel_format  = PIXEL_FORMAT_RGB_888;
}

static int ili9881c_set_pixel_format(const struct device *dev,
				     const enum display_pixel_format fmt)
{
	if (fmt == PIXEL_FORMAT_RGB_888) {
		return 0;
	}

	LOG_WRN("Unsupported pixel format 0x%08x", fmt);
	return -ENOTSUP;
}

